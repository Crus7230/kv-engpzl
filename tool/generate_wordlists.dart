import 'dart:io';

import 'package:english_words/english_words.dart' as ew;

final RegExp _lettersOnly = RegExp(r'^[a-z]+$');

// Very small safety blacklist for obvious profanity/slurs.
// Keep this list short and maintainable; add only high-confidence terms.
const Set<String> _blacklist = {
  'anal',
  'anus',
  'arse',
  'boob',
  'boobs',
  'cunt',
  'dick',
  'faggot',
  'fuck',
  'fucks',
  'fucking',
  'nigger',
  'penis',
  'porn',
  'pussy',
  'rape',
  'raped',
  'rapes',
  'shit',
  'slut',
  'whore',
};

void main() {
  final root = Directory.current.path;
  final outDir = Directory('$root/assets/wordlists');
  if (!outDir.existsSync()) {
    outDir.createSync(recursive: true);
  }

  final freq = _normalize(ew.all);
  final nouns = _normalize(ew.nouns);
  final adjectives = _normalize(ew.adjectives);
  final merged = _mergeUnique([freq, nouns, adjectives]);

  final answers4 = _pickAnswerPool(freq, length: 4, maxCount: 500);
  final answers5 = _pickAnswerPool(freq, length: 5, maxCount: 700);

  final allowed4 = _mergeUnique([
    answers4,
    _filterByLength(merged, 4),
  ]);
  final allowed5 = _mergeUnique([
    answers5,
    _filterByLength(merged, 5),
  ]);

  final crash = _filterByLengthRange(merged, minLength: 3, maxLength: 7);

  _writeList(
    File('${outDir.path}/wordle_answers_4.txt'),
    answers4,
    header:
        '# Generated by tool/generate_wordlists.dart\n# Wordle answer pool (4 letters)\n',
  );
  _writeList(
    File('${outDir.path}/wordle_answers_5.txt'),
    answers5,
    header:
        '# Generated by tool/generate_wordlists.dart\n# Wordle answer pool (5 letters)\n',
  );
  _writeList(
    File('${outDir.path}/wordle_allowed_4.txt'),
    allowed4,
    header:
        '# Generated by tool/generate_wordlists.dart\n# Wordle valid guesses (4 letters)\n',
  );
  _writeList(
    File('${outDir.path}/wordle_allowed_5.txt'),
    allowed5,
    header:
        '# Generated by tool/generate_wordlists.dart\n# Wordle valid guesses (5 letters)\n',
  );
  _writeList(
    File('${outDir.path}/crash_words.txt'),
    crash,
    header:
        '# Generated by tool/generate_wordlists.dart\n# Word Crash valid words (3-7 letters)\n',
  );

  final summary = File('${outDir.path}/summary.txt');
  summary.writeAsStringSync('''
Generated word pools
- answers_4: ${answers4.length}
- answers_5: ${answers5.length}
- allowed_4: ${allowed4.length}
- allowed_5: ${allowed5.length}
- crash_3_to_7: ${crash.length}
''');

  stdout.writeln('Word lists generated at ${outDir.path}');
  stdout.writeln(summary.readAsStringSync().trim());
}

List<String> _normalize(Iterable<String> words) {
  final set = <String>{};
  for (final raw in words) {
    final word = raw.trim().toLowerCase();
    if (!_lettersOnly.hasMatch(word)) continue;
    if (_blacklist.contains(word)) continue;
    set.add(word);
  }
  return set.toList(growable: false);
}

List<String> _mergeUnique(List<List<String>> lists) {
  final out = <String>{};
  for (final list in lists) {
    out.addAll(list);
  }
  final merged = out.toList();
  merged.sort();
  return merged;
}

List<String> _pickAnswerPool(
  List<String> frequencyList, {
  required int length,
  required int maxCount,
}) {
  final out = <String>[];
  final seen = <String>{};

  for (final word in frequencyList) {
    if (word.length != length) continue;
    if (!_isAnswerFriendly(word)) continue;
    if (seen.add(word)) {
      out.add(word.toUpperCase());
      if (out.length >= maxCount) break;
    }
  }

  return out;
}

bool _isAnswerFriendly(String word) {
  const vowels = {'a', 'e', 'i', 'o', 'u'};
  var vowelCount = 0;
  for (final ch in word.split('')) {
    if (vowels.contains(ch)) vowelCount++;
  }
  if (vowelCount == 0) return false;
  if (RegExp(r'(.)\1\1').hasMatch(word)) return false;
  return true;
}

List<String> _filterByLength(List<String> words, int length) {
  final out = <String>{};
  for (final word in words) {
    if (word.length == length) {
      out.add(word.toUpperCase());
    }
  }
  final sorted = out.toList();
  sorted.sort();
  return sorted;
}

List<String> _filterByLengthRange(
  List<String> words, {
  required int minLength,
  required int maxLength,
}) {
  final out = <String>{};
  for (final word in words) {
    if (word.length >= minLength && word.length <= maxLength) {
      out.add(word.toUpperCase());
    }
  }
  final sorted = out.toList();
  sorted.sort();
  return sorted;
}

void _writeList(File file, List<String> words, {required String header}) {
  final body = StringBuffer(header);
  for (final word in words) {
    body.writeln(word);
  }
  file.writeAsStringSync(body.toString());
}
